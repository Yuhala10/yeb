export function appText(language, key, vars) {
    const lang = language === "en" ? "en" : "fr";

    let text = TEXT[lang][key] ?? TEXT.en[key] ?? key;

    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.split(`{${name}}`).join(String(value ?? ""));
        }

        // French elision before a town name: "d'Edéa", not "de Edéa".
        if (lang === "fr") {
            text = text.replace(/\bde ([AEIOUÉÈÊaeiouéèê])/g, "d'$1");
        }
    }

    return text;
}

export function useAppText() {
    const { language } = useLanguage();

    return (key, vars) => appText(language, key, vars);
}

/*
 * A server error in the reader's language: known codes are
 * translated, other messages are shown as the server wrote
 * them (in English).
 */
export function appError(language, error) {
    const code = error?.code;

    if (code && TEXT.en[`err_${code}`]) {
        return appText(language, `err_${code}`);
    }

    return error?.message || appText(language, "error");
}
