export function goText(language, key, vars) {
    const lang = language === "en" ? "en" : "fr";

    let text = TEXT[lang][key] ?? TEXT.en[key] ?? key;

    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.split(`{${name}}`).join(String(value ?? ""));
        }
    }

    return text;
}

export function useGoText() {
    const { language } = useLanguage();

    return (key, vars) => goText(language, key, vars);
}

export function goError(language, error) {
    const code = error?.code;

    if (code && TEXT.en[`err_${code}`]) {
        return goText(language, `err_${code}`);
    }

    return error?.message || goText(language, "tryAgain");
}

// "12 min", "1 h 05"
export function goDuration(minutes, language) {
    const value = Math.max(1, Math.round(Number(minutes) || 0));

    if (value < 60) {
        return goText(language, "min", { n: value });
    }

    return goText(language, "hours", { h: Math.floor(value / 60), m: String(value % 60).padStart(2, "0") });
}
