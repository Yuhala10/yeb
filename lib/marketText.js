/*
 * The best message for an API error: the French version of
 * known codes, otherwise the server's own message.
 */
export function marketError(language, error) {
    if (error?.code === "OFFLINE") {
        return marketText(language, "offline");
    }

    const key = `err_${error?.code}`;

    if (error?.code && TEXT.en[key]) {
        return language === "fr" ? marketText(language, key) : error.message || marketText(language, key);
    }

    return error?.message || marketText(language, "errorGeneric");
}

export function marketText(language, key, vars) {
    let text = (TEXT[language] || TEXT.en)[key] ?? TEXT.en[key] ?? key;

    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.split(`{${name}}`).join(String(value ?? ""));
        }
    }

    return text;
}

export function useMarketText() {
    const { language } = useLanguage();

    return useMemo(
        () => (key, vars) => marketText(language, key, vars),
        [language]
    );
}

/*
 * "17 Oct" / "17 oct." for a YYYY-MM-DD or ISO date.
 */
export function formatDay(value, language) {
    if (!value) {
        return "";
    }

    const date = new Date(String(value).length === 10 ? `${value}T12:00:00Z` : value);

    if (Number.isNaN(date.getTime())) {
        return "";
    }

    return date.toLocaleDateString(language === "fr" ? "fr-FR" : "en-GB", {
        day: "numeric",
        month: "short",
        timeZone: "Africa/Douala",
    });
}
